const DICTS: Record<Lang, Record<string, string>> = { en, ar };

export type Vars = Record<string, string | number | undefined | null>;
export type T = (key: TKey | string, vars?: Vars) => string;

interface I18n {
  lang: Lang;
  dir: "ltr" | "rtl";
  setLang: (l: Lang) => void;
  t: T;
}

const Ctx = createContext<I18n | null>(null);

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem("zr.lang");
    if (saved === "ar" || saved === "en") return saved;
  } catch {
    /* storage blocked: fall through */
  }
  return navigator.language?.startsWith("ar") ? "ar" : "en";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang);
  const dir = lang === "ar" ? "rtl" : "ltr";

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = dir;
  }, [lang, dir]);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem("zr.lang", l);
    } catch {
      /* ignore */
    }
  }, []);

  const t = useCallback<T>(
    (key, vars) => {
      // A count of one reads "1 record", not "1 records": "<key>.one" in this language, when it has one.
      const one = vars && String(vars.n) === "1" ? DICTS[lang][`${key}.one`] : undefined;
      const text = one ?? DICTS[lang][key] ?? DICTS.en[key] ?? key;
      if (!vars) return text;
      return text.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? "").toString());
    },
    [lang],
  );

  const value = useMemo(() => ({ lang, dir, setLang, t }) as I18n, [lang, dir, setLang, t]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18n {
  const ctx = useContext(Ctx);
  if (!ctx) throw new Error("useI18n outside provider");
  return ctx;
}
